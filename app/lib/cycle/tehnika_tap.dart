/// Отбор вопросов под тап «здесь был приём недели?».
///
/// Детерминированно по `questionId`, а не случайно: иначе тест невоспроизводим,
/// а один и тот же вопрос при повторной встрече ведёт себя по-разному.
library;

/// FNV-1a 32 бита. Взята ради устойчивости результата между запусками:
/// `String.hashCode` в Dart этого не гарантирует.
int fnv1a(String s) {
  var hash = 0x811c9dc5;
  for (final c in s.codeUnits) {
    hash ^= c & 0xff;
    hash = (hash * 0x01000193) & 0xffffffff;
    if (c > 0xff) {
      hash ^= (c >> 8) & 0xff;
      hash = (hash * 0x01000193) & 0xffffffff;
    }
  }
  return hash;
}

/// Каждый третий вопрос — из постановки T4a.
const int kTapEveryNth = 3;

/// Тап показывается на эталонных вопросах приёма **всегда** и на каждом третьем
/// из остальных.
///
/// Эталонные вопросы редки (91 на корпус), и без гарантии тап на них почти
/// никогда бы не попадал — то есть вердикт игрок не увидел бы ни разу. Но
/// показывать тап **только** на них нельзя: тогда сам факт тапа означал бы
/// «да», и угадывать снова нечего.
bool shouldAskTehnika(String questionId, {required bool inStandard}) =>
    inStandard || fnv1a(questionId) % kTapEveryNth == 0;
